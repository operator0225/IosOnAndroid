#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_spirv_has_valid_magic_number() {
        // 0x07230203 is SPIR-V's magic number, the same check any SPIR-V
        // consumer (including vkCreateShaderModule) does first.
        assert_eq!(DOUBLE_SPIRV[0], 0x0723_0203);
    }

    #[test]
    fn embedded_spirv_matches_recorded_word_count() {
        assert_eq!(DOUBLE_SPIRV.len(), 219);
    }
}
